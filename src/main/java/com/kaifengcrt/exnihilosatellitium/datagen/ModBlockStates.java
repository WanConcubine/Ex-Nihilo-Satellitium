package com.kaifengcrt.exnihilosatellitium.datagen;

import com.kaifengcrt.exnihilosatellitium.ExNihiloSatellitium;
import com.kaifengcrt.exnihilosatellitium.common.block.SieveBlock;
import com.kaifengcrt.exnihilosatellitium.common.material.OreMaterial;
import com.kaifengcrt.exnihilosatellitium.common.material.OreMaterials;
import com.kaifengcrt.exnihilosatellitium.registry.ModBlocks;
import com.kaifengcrt.exnihilosatellitium.registry.ModOreBlocks;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.data.PackOutput;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.neoforged.neoforge.client.model.generators.BlockStateProvider;
import net.neoforged.neoforge.client.model.generators.ModelFile;
import net.neoforged.neoforge.common.data.ExistingFileHelper;

/**
 * Blockstates and the mechanical block models.
 *
 * <p>Hand-authored geometry stays a normal file: {@code barrel_base},
 * {@code crucible_base}, the three shared {@code ore_*_block} models, the sieve
 * frame/mesh models and the four 32×32 machine models. Everything that is just
 * "parent + a few textures" (12 barrels, 12 crucibles, dust, crushed, infested
 * leaves) is generated here, together with all 71 blockstates.</p>
 *
 * <p>Item models are generated by {@link ModItemModels}; the two providers must be
 * registered in that order so the item provider can validate the block-item parents
 * against the models were generated here (the {@link ExistingFileHelper} learns
 * about them through {@code trackGenerated}).</p>
 */
public final class ModBlockStates extends BlockStateProvider {

    public ModBlockStates(final PackOutput output, final ExistingFileHelper helper) {
        super(output, ExNihiloSatellitium.MOD_ID, helper);
    }

    @Override
    protected void registerStatesAndModels() {
        for (final WoodTypes.Wood wood : WoodTypes.ALL) {
            barrel(wood);
            crucible(wood);
        }
        stoneBarrel();
        porcelainCrucibles();

        cubeBlock(ModBlocks.DUST.get());
        cubeBlock(ModBlocks.CRUSHED_NETHERRACK.get());
        cubeBlock(ModBlocks.CRUSHED_END_STONE.get());
        infestedLeaves();

        sieve();
        machines();
        oreBlocks();
        witchWater();
    }

    // -------------------------------------------------------------- barrels

    private void barrel(final WoodTypes.Wood wood) {
        final ModelFile model = models()
                .withExistingParent(wood.barrel(), modLoc("block/barrel_base"))
                .texture("particle", mcLoc("block/" + wood.planksTexture()))
                .texture("side", mcLoc("block/" + wood.planksTexture()))
                .texture("top", mcLoc("block/" + wood.planksTexture()))
                .texture("inner", mcLoc("block/" + wood.strippedTexture()))
                .texture("bottom", mcLoc("block/" + wood.strippedTexture()));
        simpleBlock(block(wood.barrel()), model);
    }

    /** Stone barrel: stone body, smooth stone lid, stone inside. */
    private void stoneBarrel() {
        final ModelFile model = models()
                .withExistingParent("stone_barrel", modLoc("block/barrel_base"))
                .texture("particle", mcLoc("block/stone"))
                .texture("side", mcLoc("block/stone"))
                .texture("top", mcLoc("block/smooth_stone"))
                .texture("inner", mcLoc("block/stone"))
                .texture("bottom", mcLoc("block/stone"));
        simpleBlock(block("stone_barrel"), model);
    }

    // ------------------------------------------------------------ crucibles

    private void crucible(final WoodTypes.Wood wood) {
        final ModelFile model = models()
                .withExistingParent(wood.crucible(), modLoc("block/crucible_base"))
                .texture("particle", mcLoc("block/" + wood.logTexture()))
                .texture("side", mcLoc("block/" + wood.logTexture()))
                .texture("top", mcLoc("block/" + wood.logTopTexture()))
                .texture("bottom", mcLoc("block/" + wood.logTexture()))
                .texture("inside", mcLoc("block/" + wood.strippedTexture()));
        simpleBlock(block(wood.crucible()), model);
    }

    /** The fired and unfired porcelain crucibles: whole body uses our own texture. */
    private void porcelainCrucibles() {
        for (final String name : new String[]{"crucible", "unfired_crucible"}) {
            final ResourceLocation texture = modLoc("block/" + name);
            final ModelFile model = models()
                    .withExistingParent(name, modLoc("block/crucible_base"))
                    .texture("particle", texture)
                    .texture("side", texture)
                    .texture("top", texture)
                    .texture("bottom", texture)
                    .texture("inside", texture);
            simpleBlock(block(name), model);
        }
    }

    // ----------------------------------------------------------- flat cubes

    /** Plain cube with {@code all} pointing at our own texture. */
    private void cubeBlock(final Block block) {
        final String name = key(block);
        simpleBlock(block, models().cubeAll(name, modLoc("block/" + name)));
    }

    private void infestedLeaves() {
        simpleBlock(ModBlocks.INFESTED_LEAVES.get(),
                models().withExistingParent("infested_leaves", mcLoc("block/oak_leaves")));
    }

    // ---------------------------------------------------------------- sieve

    /** Frame always, plus one mesh layer per {@link SieveBlock#MESH} value. */
    private void sieve() {
        final Block block = ModBlocks.SIEVE.get();
        getMultipartBuilder(block)
                .part()
                .modelFile(models().getExistingFile(modLoc("block/sieve_frame")))
                .addModel()
                .end()
                .part()
                .modelFile(models().getExistingFile(modLoc("block/sieve_mesh_wood")))
                .addModel()
                .condition(SieveBlock.MESH, 1)
                .end()
                .part()
                .modelFile(models().getExistingFile(modLoc("block/sieve_mesh_silk")))
                .addModel()
                .condition(SieveBlock.MESH, 2)
                .end()
                .part()
                .modelFile(models().getExistingFile(modLoc("block/sieve_mesh_iron")))
                .addModel()
                .condition(SieveBlock.MESH, 3)
                .end();
    }

    // ------------------------------------------------------------- machines

    private void machines() {
        for (final String name : new String[]{"electric_sieve", "electric_hammer", "fuel_sieve", "fuel_hammer"}) {
            simpleBlock(block(name), models().getExistingFile(modLoc("block/" + name)));
        }
    }

    // ------------------------------------------------------------ ore blocks

    /** Every material's three ore-block states share one model per kind. */
    private void oreBlocks() {
        for (final OreMaterial material : OreMaterials.all()) {
            for (final String kind : ModOreBlocks.KINDS) {
                simpleBlock(block(material.id() + "_ore_" + kind),
                        models().getExistingFile(modLoc("block/ore_" + kind + "_block")));
            }
        }
    }

    /** The witch-water source block renders as water; its colour comes from the FluidType. */
    private void witchWater() {
        simpleBlock(ModBlocks.WITCH_WATER.get(), models().getExistingFile(mcLoc("block/water")));
    }

    // --------------------------------------------------------------- helpers

    private static String key(final Block block) {
        return BuiltInRegistries.BLOCK.getKey(block).getPath();
    }

    private static Block block(final String path) {
        final Block block = BuiltInRegistries.BLOCK.get(
                ResourceLocation.fromNamespaceAndPath(ExNihiloSatellitium.MOD_ID, path));
        if (block == Blocks.AIR) {
            throw new IllegalStateException("datagen blockstate references unknown block " + path);
        }
        return block;
    }
}
